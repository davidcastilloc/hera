fn main() {
    // Build the app
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .codegen(tauri_build::CodegenContext::new())
            .plugin(
                "app-menu",
                tauri_build::InlinedPlugin::new().commands(&["show", "hide", "show_window"]),
            )
            .plugin(
                "config",
                tauri_build::InlinedPlugin::new().commands(&[
                    "get_storage_dir",
                    "get_config",
                    "set_config",
                ]),
            )
            .plugin(
                "cover",
                tauri_build::InlinedPlugin::new().commands(&["get_cover"]),
            )
            .plugin(
                "database",
                tauri_build::InlinedPlugin::new().commands(&[
                    "scan_library",
                    "get_all_tracks",
                    "remove_tracks",
                    "get_tracks",
                    "get_track",
                    "update_track",
                    "get_artists",
                    "get_artist_tracks",
                    "get_compilation_albums",
                    "has_compilations",
                    "get_all_playlists",
                    "get_playlist",
                    "create_playlist",
                    "rename_playlist",
                    "set_playlist_tracks",
                    "export_playlist",
                    "delete_playlist",
                    "reset",
                ]),
            )
            .plugin(
                "default-view",
                tauri_build::InlinedPlugin::new().commands(&["set"]),
            )
            .plugin(
                "hera-dj",
                tauri_build::InlinedPlugin::new().commands(&[
                    "compute_style_dna",
                    "export_crate",
                    "build_dj_set_spine",
                    "get_cloudflare_edge_radar",
                    "chat_copilot",
                    "probe_ai_backend",
                    "list_ai_backends",
                    "scan_ai_connectivity",
                    "resolve_harmonic_bridge",
                    "download_p2p_track",
                ]),
            )
            .plugin(
                "sleepblocker",
                tauri_build::InlinedPlugin::new().commands(&["enable", "disable"]),
            ),
    )
    .expect("Failed to run tauri-build");
}
