const HERA_TYPINGS_HEADER: &str = "// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs) via hera-ipc. Do not edit manually.\n\n";
const REEXPORT_STMT: &str = "export * from './hera-typings';";

fn export_decl<T: TS>(cfg: &Config) -> String {
    let raw = T::decl(cfg);
    let trimmed = raw.trim().trim_end_matches(';');
    if trimmed.starts_with("export ") {
        format!("{trimmed};")
    } else {
        format!("export {trimmed};")
    }
}

/// Generates `hera-typings.ts` deterministically and ensures `typings.ts` re-exports it.
pub fn export_hera_typescript_bindings(generated_dir: &Path) -> Result<String, String> {
    let cfg = Config::default();
    let mut decls = vec![
        export_decl::<AgentAttachment>(&cfg),
        export_decl::<AgentFollowupAction>(&cfg),
        export_decl::<AgentMessageView>(&cfg),
        export_decl::<AgentRuntimeStatus>(&cfg),
        export_decl::<AgentSessionSummary>(&cfg),
        export_decl::<AgentStreamEvent>(&cfg),
        export_decl::<AgentToolExecutionStep>(&cfg),
        export_decl::<AgentToolStepView>(&cfg),
        export_decl::<AgentUiSyncEvent>(&cfg),
        export_decl::<AiBackendOption>(&cfg),
        export_decl::<AiConnectivityOnboardingReport>(&cfg),
        export_decl::<AnchorArtistStat>(&cfg),
        export_decl::<CloudflareEdgeCapabilities>(&cfg),
        export_decl::<CloudflareFreeAiTurnRequest>(&cfg),
        export_decl::<CloudflareFreeAiTurnResponse>(&cfg),
        export_decl::<CloudflareServicePrimitive>(&cfg),
        export_decl::<CreateAgentSessionRequest>(&cfg),
        export_decl::<DetectedCliAgent>(&cfg),
        export_decl::<DetectedLocalServer>(&cfg),
        export_decl::<DjStyleDnaProfile>(&cfg),
        export_decl::<DjStyleDnaRequest>(&cfg),
        export_decl::<DownloadP2PTrackRequest>(&cfg),
        export_decl::<DownloadP2PTrackResponse>(&cfg),
        export_decl::<ExportCrateRequest>(&cfg),
        export_decl::<ExportCrateResponse>(&cfg),
        export_decl::<ExportTrackItem>(&cfg),
        export_decl::<HarmonicBridgeStep>(&cfg),
        export_decl::<HotCuePoint>(&cfg),
        export_decl::<McpHostIntegrationGuide>(&cfg),
        export_decl::<MediaMixProfile>(&cfg),
        export_decl::<ProbeAiBackendResponse>(&cfg),
        export_decl::<PushVirtualDjLiveCrateRequest>(&cfg),
        export_decl::<PushVirtualDjLiveCrateResponse>(&cfg),
        export_decl::<ResolveHarmonicBridgeRequest>(&cfg),
        export_decl::<ResolveHarmonicBridgeResponse>(&cfg),
        export_decl::<SetMiniOverlayModeRequest>(&cfg),
        export_decl::<SetMiniOverlayModeResponse>(&cfg),
        export_decl::<StartAgentTurnRequest>(&cfg),
        export_decl::<StartAgentTurnResponse>(&cfg),
        export_decl::<SwarmCatalogItem>(&cfg),
        export_decl::<SwarmMoqHarmonicEvent>(&cfg),
        export_decl::<SwarmProtectionStatus>(&cfg),
        export_decl::<UpdateAgentSessionRequest>(&cfg),
        export_decl::<VirtualDjNowPlaying>(&cfg),
    ];
    decls.sort();

    let mut out = String::from(HERA_TYPINGS_HEADER);
    out.push_str(&decls.join("\n\n"));
    out.push('\n');

    std::fs::create_dir_all(generated_dir).map_err(|e| e.to_string())?;
    let hera_typings_path = generated_dir.join("hera-typings.ts");
    std::fs::write(&hera_typings_path, &out).map_err(|e| e.to_string())?;

    let typings_path = generated_dir.join("typings.ts");
    if typings_path.exists() {
        let existing = std::fs::read_to_string(&typings_path).map_err(|e| e.to_string())?;
        if !existing.contains("export * from './hera-typings'")
            && !existing.contains("export * from \"./hera-typings\"")
        {
            let mut updated = existing.trim_end().to_string();
            updated.push_str("\n\n");
            updated.push_str(REEXPORT_STMT);
            updated.push('\n');
            std::fs::write(&typings_path, updated).map_err(|e| e.to_string())?;
        }
    }

    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::export_hera_typescript_bindings;
    use std::path::Path;

    #[test]
    fn test_export_hera_typescript_bindings() {
        let generated_dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/generated");
        let generated = export_hera_typescript_bindings(&generated_dir)
            .expect("export hera-typings.ts and typings.ts re-export");

        for expected in [
            "export type DjStyleDnaProfile =",
            "export type ResolveHarmonicBridgeResponse =",
            "export type SetMiniOverlayModeResponse =",
            "export type AgentSessionSummary =",
            "export type AgentRuntimeStatus =",
            "message_count: number",
            "supported_backends: Array<AiBackendOption>",
        ] {
            assert!(generated.contains(expected), "missing `{expected}`");
        }
        assert!(!generated.contains("bigint"), "unexpected bigint in generated TS");

        let typings = std::fs::read_to_string(generated_dir.join("typings.ts"))
            .expect("read src/generated/typings.ts");
        for core_sym in ["export type Track =", "export type SortBy =", "hera-typings"] {
            assert!(typings.contains(core_sym), "typings.ts missing `{core_sym}`");
        }
    }
}
